// Transparent mode for harnesses that source a file before every shell
// command (Claude Code's CLAUDE_ENV_FILE). The hook-owned daemon maintains one
// owner-only shell file; the harness-owned env file only ever receives a line
// that sources it. Nothing is evaluated per command by Phase itself: the shell
// re-reads the file, so approvals, recycles, and `phase ai disable` take effect
// on the next command without restarting the harness.
const (
	runtimeEnvironmentFile       = "env.sh"
	runtimeEnvironmentJSONFile   = "env.json"
	runtimeEnvironmentStatusFile = "env-status.json"
	runtimeEnvironmentSchema     = 1
	proxyBlockBegin              = "# >>> phase-ai proxy routing (only while the proxy process is alive)"
	proxyBlockEnd                = "# <<< phase-ai proxy routing"
	// Session start and prompt submission wait at most this long for the daemon
	// so a slow or unreachable Console never stalls ordinary work.
	hookKickBudget = 1500 * time.Millisecond
)

// runtimeEnvironmentGOOS picks the liveness guard; tests override it.
var runtimeEnvironmentGOOS = runtime.GOOS

// hookRuntimeMarker tags an environment published by the shared hook
// daemon. Its value is bound to that daemon's proxy URL, so an environment from
// a launcher such as phase ai run, which replaces the proxy, never matches.
const hookRuntimeMarker = "PHASE_AI_HOOK_RUNTIME"

func hookRuntimeMarkerValue(proxyURL string) string {
	digest := sha256.Sum256([]byte(proxyURL))
	return hex.EncodeToString(digest[:16])
}

type runtimeEnvironmentStatus struct {
	Schema      int                          `json:"schema"`
	PID         int                          `json:"pid"`
	Generation  string                       `json:"generation"`
	StartedAt   time.Time                    `json:"startedAt,omitempty"`
	ProxyLive   bool                         `json:"proxyLive"`
	Connections []aiproxy.EndpointConnection `json:"connections"`
}

// runtimeEnvironmentJSON is the machine-readable twin of env.sh for harnesses
// that inject environment through a plugin (OpenCode). Set holds decoys and
// adapter endpoints that stay exported; Proxy holds routing and trust keys
// that apply only while the proxy process PID is alive and ProxyLive is true.
type runtimeEnvironmentJSON struct {
	Schema    int               `json:"schema"`
	PID       int               `json:"pid"`
	ProxyLive bool              `json:"proxyLive"`
	Set       map[string]string `json:"set"`
	Proxy     map[string]string `json:"proxy"`
	Unset     []string          `json:"unset"`
}

type hookRuntimeHealth struct {
	ready       bool
	starting    bool
	reason      string
	connections []aiproxy.EndpointConnection
	// A recent session recycle of the running daemon, so the Agent learns why
	// a command may have failed and that a retry is enough.
	refreshedAt   time.Time
	refreshReason string
}

// renderRuntimeEnvironment produces the POSIX shell a harness sources before each
// command. Proxy routing, Phase runtime markers, and trust overrides live inside
// a liveness guard on the issuing proxy, so a crashed proxy can never strand
// a shell behind a dead port. Decoys, adapter endpoints, and explicit unsets
// stay outside the guard: while Phase AI is enabled, provider tools either reach
// the Phase proxy or fail on the decoy. They never fall through to an ambient
// credential by accident.
func renderRuntimeEnvironment(pid int, plan phaseproxy.ProcessEnvironmentPlan, proxyLive bool) (string, error) {
	if proxyLive && pid <= 0 {
		return "", errors.New("Phase AI proxy PID is required for a live environment")
	}
	var guard string
	if proxyLive {
		var err error
		if guard, err = proxyLivenessGuard(pid, plan); err != nil {
			return "", err
		}
	}
	keys := make([]string, 0, len(plan.Set))
	for key, value := range plan.Set {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return "", fmt.Errorf("environment key %q is not a valid shell identifier", key)
		}
		if strings.ContainsAny(value, "\x00\r\n") {
			return "", fmt.Errorf("environment key %s has an unsafe value", key)
		}
		keys = append(keys, key)
	}
	sort.Strings(keys)
	unsets := append([]string(nil), plan.Unset...)
	sort.Strings(unsets)
	for _, key := range unsets {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return "", fmt.Errorf("environment unset %q is not a valid shell identifier", key)
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "# Phase AI shell environment (schema %d). Generated by the Phase CLI; do not edit.\n", runtimeEnvironmentSchema)
	out.WriteString("# A harness sources this file before each shell command. Proxy routing applies\n")
	out.WriteString("# only while the Phase AI proxy process is alive. Decoy credentials stay exported\n")
	out.WriteString("# so ambient provider credentials are never substituted for a Phase-managed\n")
	out.WriteString("# Connection while Phase AI is enabled; `phase ai disable` removes this file.\n")
	if len(unsets) > 0 {
		out.WriteString("unset " + strings.Join(unsets, " ") + "\n")
	}
	for _, key := range keys {
		if phaseproxy.RuntimeControlEnvironmentKey(key) {
			continue
		}
		fmt.Fprintf(&out, "export %s=%s\n", key, ai.QuotePOSIXShell(plan.Set[key]))
	}
	if proxyLive {
		out.WriteString(proxyBlockBegin + "\n")
		out.WriteString("if " + guard + "; then\n")
		for _, key := range keys {
			if !phaseproxy.RuntimeControlEnvironmentKey(key) {
				continue
			}
			fmt.Fprintf(&out, "  export %s=%s\n", key, ai.QuotePOSIXShell(plan.Set[key]))
		}
		out.WriteString("fi\n")
		out.WriteString(proxyBlockEnd + "\n")
	} else {
		out.WriteString("# The Phase AI proxy is not running: Phase-managed provider commands fail until it recovers.\n")
	}
	// Always end successfully so a harness that chains the sourced file with the
	// command (`. file && command`) is never blocked by this file.
	out.WriteString(":\n")
	return out.String(), nil
}

// proxyLivenessGuard keeps routing on only while the proxy is alive. Git
// Bash cannot signal native Windows PIDs, so on Windows it probes the port.
func proxyLivenessGuard(pid int, plan phaseproxy.ProcessEnvironmentPlan) (string, error) {
	if runtimeEnvironmentGOOS != "windows" {
		return fmt.Sprintf("kill -0 %d 2>/dev/null", pid), nil
	}
	raw := ""
	for _, key := range []string{"HTTPS_PROXY", "HTTP_PROXY", "https_proxy", "http_proxy"} {
		if raw = plan.Set[key]; raw != "" {
			break
		}
	}
	if raw == "" {
		return "false", nil
	}
	proxyURL, err := url.Parse(raw)
	if err != nil {
		return "", errors.New("Phase AI proxy URL is invalid")
	}
	host, port, err := net.SplitHostPort(proxyURL.Host)
	number, portErr := strconv.Atoi(port)
	if err != nil || portErr != nil || net.ParseIP(host).To4() == nil || number < 1 || number > 65535 {
		return "", fmt.Errorf("Phase AI proxy address %q is not an IPv4 address and port", proxyURL.Host)
	}
	// true is a regular builtin, so a refused connection fails the test without
	// ending a non-interactive shell.
	return fmt.Sprintf("true 2>/dev/null </dev/tcp/%s/%s", host, port), nil
}

// stripProxyBlock removes the proxy-routing block from rendered content.
// Hooks use it to retire routing for a daemon that is gone without needing the
// original environment plan.
func stripProxyBlock(content string) string {
	begin := strings.Index(content, proxyBlockBegin+"\n")
	if begin < 0 {
		return content
	}
	end := strings.Index(content[begin:], proxyBlockEnd+"\n")
	if end < 0 {
		return content
	}
	stripped := content[:begin] + content[begin+end+len(proxyBlockEnd)+1:]
	if !strings.Contains(stripped, "proxy is not running") {
		stripped = strings.TrimSuffix(stripped, ":\n") +
			"# The Phase AI proxy is not running: Phase-managed provider commands fail until it recovers.\n:\n"
	}
	return stripped
}

func runtimeEnvironmentPath(directory string) string {
	return filepath.Join(directory, runtimeEnvironmentFile)
}

func runtimeEnvironmentStatusPath(directory string) string {
	return filepath.Join(directory, runtimeEnvironmentStatusFile)
}

func runtimeEnvironmentJSONPath(directory string) string {
	return filepath.Join(directory, runtimeEnvironmentJSONFile)
}

// renderRuntimeEnvironmentJSON splits the plan the same way renderRuntimeEnvironment
// does: decoys, adapters and unsets always apply; proxy routing only while the
// issuing process is alive. The plugin that reads it checks the PID itself.
func renderRuntimeEnvironmentJSON(pid int, plan phaseproxy.ProcessEnvironmentPlan, proxyLive bool) (runtimeEnvironmentJSON, error) {
	if proxyLive && pid <= 0 {
		return runtimeEnvironmentJSON{}, errors.New("Phase AI proxy PID is required for a live environment")
	}
	payload := runtimeEnvironmentJSON{Schema: runtimeEnvironmentSchema, PID: pid, ProxyLive: proxyLive, Set: map[string]string{}, Proxy: map[string]string{}, Unset: []string{}}
	for key, value := range plan.Set {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return runtimeEnvironmentJSON{}, fmt.Errorf("environment key %q is not a valid shell identifier", key)
		}
		if strings.ContainsAny(value, "\x00\r\n") {
			return runtimeEnvironmentJSON{}, fmt.Errorf("environment key %s has an unsafe value", key)
		}
		if phaseproxy.RuntimeControlEnvironmentKey(key) {
			if proxyLive {
				payload.Proxy[key] = value
			}
			continue
		}
		payload.Set[key] = value
	}
	for _, key := range plan.Unset {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return runtimeEnvironmentJSON{}, fmt.Errorf("environment unset %q is not a valid shell identifier", key)
		}
		payload.Unset = append(payload.Unset, key)
	}
	sort.Strings(payload.Unset)
	return payload, nil
}

// writeRuntimeEnvironment publishes the sourced environment and its printable
// status. The daemon calls it when a proxy cycle becomes ready (live) and when
// that cycle ends (degraded, decoys only).
func writeRuntimeEnvironment(directory string, pid int, generation string, startedAt time.Time,
	plan phaseproxy.ProcessEnvironmentPlan, connections []aiproxy.EndpointConnection, proxyLive bool) error {
	if proxyURL := firstMapValue(plan.Set, "HTTPS_PROXY", "HTTP_PROXY", "https_proxy", "http_proxy"); proxyURL != "" {
		plan.Set = maps.Clone(plan.Set)
		plan.Set[hookRuntimeMarker] = hookRuntimeMarkerValue(proxyURL)
	}
	content, err := renderRuntimeEnvironment(pid, plan, proxyLive)
	if err != nil {
		return err
	}
	payload, err := renderRuntimeEnvironmentJSON(pid, plan, proxyLive)
	if err != nil {
		return err
	}
	if err := writeOwnerOnlyBytes(runtimeEnvironmentPath(directory), []byte(content)); err != nil {
		return err
	}
	if err := writeOwnerOnlyJSON(runtimeEnvironmentJSONPath(directory), payload); err != nil {
		return err
	}
	if connections == nil {
		connections = []aiproxy.EndpointConnection{}
	}
	return writeOwnerOnlyJSON(runtimeEnvironmentStatusPath(directory), runtimeEnvironmentStatus{
		Schema: runtimeEnvironmentSchema, PID: pid, Generation: generation, StartedAt: startedAt,
		ProxyLive: proxyLive, Connections: connections,
	})
}

// removeRuntimeEnvironmentFiles is the `phase ai disable` exit: the next shell
// command sources nothing and runs with ambient credentials.
func removeRuntimeEnvironmentFiles() error {
	directory, err := hookRuntimeDir()
	if err != nil {
		return err
	}
	var errs []error
	for _, path := range []string{runtimeEnvironmentPath(directory), runtimeEnvironmentJSONPath(directory), runtimeEnvironmentStatusPath(directory)} {
		if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// inspectHookRuntime reports daemon health from local files only: no network,
// no keyring. Hooks call it on every prompt.
func inspectHookRuntime(directory string) hookRuntimeHealth {
	var health hookRuntimeHealth
	state, err := readHookRuntimeState(filepath.Join(directory, hookRuntimeStateFile))
	if err == nil && validateHookRuntimeState(state, "") == nil {
		health.ready = true
		var status runtimeEnvironmentStatus
		if readOwnerOnlyJSON(runtimeEnvironmentStatusPath(directory), &status) == nil && status.PID == state.PID && status.ProxyLive {
			health.connections = status.Connections
		}
		health.refreshedAt, health.refreshReason = lastSessionRefresh(directory, time.Now(), refreshNoticeWindow)
		return health
	}
	// A daemon recycling its session has withdrawn its state as if starting.
	lock, lockErr := readHookRuntimeLock(filepath.Join(directory, hookRuntimeLockFile))
	if lockErr == nil && hookRuntimeStarting(lock) {
		health.starting = true
		return health
	}
	failures, _ := filepath.Glob(filepath.Join(directory, "runtime-*.error.json"))
	for _, path := range failures {
		var failure hookRuntimeFailure
		if readOwnerOnlyJSON(path, &failure) == nil && failure.Reason == "authentication" {
			health.reason = failure.Reason
		}
	}
	return health
}

// hookRuntimeStarting reports a lock held by a live daemon that has no state
// to show yet: it is starting, or it withdrew its state to recycle its
// session. Either lasts seconds, so a lock that says so for longer is stale.
func hookRuntimeStarting(lock hookRuntimeLock) bool {
	return lock.PID > 0 && processIsAlive(lock.PID) &&
		(time.Since(lock.CreatedAt) < 2*hookStartTimeout || time.Since(lock.RecyclingAt) < 2*hookStartTimeout)
}

// reconcileRuntimeEnvironment retires proxy routing in the sourced file when the
// daemon that published it is gone. The PID guard already protects every
// command; this bounds PID reuse to one prompt. It holds the runtime lock, so
// a replacement daemon publishes either before the check or after the rewrite.
func reconcileRuntimeEnvironment(directory string, health hookRuntimeHealth) {
	if health.ready || hookPhaseAIDisabled() {
		return
	}
	_ = withHookRuntimeLock(directory, func() error {
		var status runtimeEnvironmentStatus
		if readOwnerOnlyJSON(runtimeEnvironmentStatusPath(directory), &status) != nil || !status.ProxyLive {
			return nil
		}
		if status.PID > 0 && processIsAlive(status.PID) {
			return nil
		}
		content, err := os.ReadFile(runtimeEnvironmentPath(directory))
		if err != nil {
			return nil
		}
		if err := writeOwnerOnlyBytes(runtimeEnvironmentPath(directory), []byte(stripProxyBlock(string(content)))); err != nil {
			return nil
		}
		var payload runtimeEnvironmentJSON
		if readOwnerOnlyJSON(runtimeEnvironmentJSONPath(directory), &payload) == nil && payload.Schema == runtimeEnvironmentSchema {
			payload.ProxyLive = false
			payload.Proxy = map[string]string{}
			_ = writeOwnerOnlyJSON(runtimeEnvironmentJSONPath(directory), payload)
		}
		status.ProxyLive = false
		return writeOwnerOnlyJSON(runtimeEnvironmentStatusPath(directory), status)
	})
	// disable may have removed the files while they were rewritten.
	if hookPhaseAIDisabled() {
		_ = removeRuntimeEnvironmentFiles()
	}
}

// kickHarnessRuntime is the harness-neutral form used by every transparent-mode
// integration (Claude Code hooks, the OpenCode plugin). A daemon still starting
// or recycling gets the lease too, so it does not idle out if it becomes ready
// only after this wait and the session's next prompt.
func kickHarnessRuntime(ctx context.Context, directory, harness, sessionID string, budget time.Duration) hookRuntimeHealth {
	if ctx == nil {
		ctx = context.Background()
	}
	kickContext, cancel := context.WithTimeout(ctx, budget)
	defer cancel()
	_ = ensureHarnessRuntimeReady(kickContext)
	health := inspectHookRuntime(directory)
	if health.ready || health.starting {
		_ = registerHarnessLease(harness, sessionID, time.Now().UTC().Add(harnessSessionLeaseTTL))
	}
	reconcileRuntimeEnvironment(directory, health)
	return health
}

// runtimeStatusLine is the printable, credential-free status handed
// to the Agent at session start and on every prompt.
func runtimeStatusLine(health hookRuntimeHealth) string {
	switch {
	case health.ready && len(health.connections) == 0:
		return "Phase AI: proxy ready, but this Workflow has no Connections yet. When the human asks for a Phase-managed service, load the phase-cli skill and create a setup request."
	case health.ready:
		names := make([]string, 0, len(health.connections))
		for _, connection := range health.connections {
			label := strings.TrimSpace(connection.Name)
			if label == "" {
				label = connection.ConnectionID
			}
			names = append(names, label+" ("+connection.ServiceType+")")
		}
		return "Phase AI: proxy ready. Shell commands automatically use Phase-managed credentials for: " + strings.Join(names, ", ") + ". Run provider tools directly; no wrapper or phase ai exec is needed." + sessionRefreshNotice(health.refreshedAt, health.refreshReason)
	case health.starting:
		return "Phase AI: proxy is starting. A Phase-managed provider command issued before it is ready fails with a credential error; retry it. Other work is unaffected."
	case health.reason == "authentication":
		return "Phase AI: unavailable because the Phase login is invalid or expired; the human must run phase auth --mode token. Phase-managed provider commands fail until then, other work is unaffected. Do not substitute other credentials."
	default:
		return "Phase AI: proxy unavailable. Phase-managed provider commands fail until it recovers, other work is unaffected. Tell the human; do not substitute other credentials, disable Phase, or restart the harness."
	}
}
