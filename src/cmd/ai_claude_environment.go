// Transparent mode for harnesses that source a file before every shell
// command (Claude Code's CLAUDE_ENV_FILE). The hook-owned daemon maintains one
// owner-only shell file; the harness-owned env file only ever receives a line
// that sources it. Nothing is evaluated per command by Phase itself: the shell
// re-reads the file, so approvals, recycles, and `phase ai disable` take effect
// on the next command without restarting the harness.
const (
	claudeEnvironmentFile       = "env.sh"
	claudeEnvironmentJSONFile   = "env.json"
	claudeEnvironmentStatusFile = "env-status.json"
	claudeEnvironmentSchema     = 1
	claudeEnvironmentLoaderMark = "# phase-ai-env-loader v1"
	claudeProxyBlockBegin       = "# >>> phase-ai proxy routing (only while the proxy process is alive)"
	claudeProxyBlockEnd         = "# <<< phase-ai proxy routing"
	// Session start and prompt submission wait at most this long for the daemon
	// so a slow or unreachable Console never stalls ordinary work.
	claudeHookKickBudget = 1500 * time.Millisecond
)

type claudeEnvironmentStatus struct {
	Schema      int                          `json:"schema"`
	PID         int                          `json:"pid"`
	Generation  string                       `json:"generation"`
	StartedAt   time.Time                    `json:"startedAt,omitempty"`
	ProxyLive   bool                         `json:"proxyLive"`
	Connections []aiproxy.EndpointConnection `json:"connections"`
}

// claudeEnvironmentJSON is the machine-readable twin of env.sh for harnesses
// that inject environment through a plugin (OpenCode). Set holds decoys and
// adapter endpoints that stay exported; Proxy holds routing and trust keys
// that apply only while the proxy process PID is alive and ProxyLive is true.
type claudeEnvironmentJSON struct {
	Schema    int               `json:"schema"`
	PID       int               `json:"pid"`
	ProxyLive bool              `json:"proxyLive"`
	Set       map[string]string `json:"set"`
	Proxy     map[string]string `json:"proxy"`
	Unset     []string          `json:"unset"`
}

type claudeRuntimeHealth struct {
	ready       bool
	starting    bool
	reason      string
	connections []aiproxy.EndpointConnection
	// A recent session recycle of the running daemon, so the Agent learns why
	// a command may have failed and that a retry is enough.
	refreshedAt   time.Time
	refreshReason string
}

// renderClaudeEnvironment produces the POSIX shell a harness sources before each
// command. Proxy routing, Phase runtime markers, and trust overrides live inside
// a liveness guard on the issuing proxy PID, so a crashed proxy can never strand
// a shell behind a dead port. Decoys, adapter endpoints, and explicit unsets
// stay outside the guard: while Phase AI is enabled, provider tools either reach
// the Phase proxy or fail on the decoy. They never fall through to an ambient
// credential by accident.
func renderClaudeEnvironment(pid int, plan phaseproxy.ProcessEnvironmentPlan, proxyLive bool) (string, error) {
	if proxyLive && pid <= 0 {
		return "", errors.New("Phase AI proxy PID is required for a live environment")
	}
	keys := make([]string, 0, len(plan.Set))
	for key, value := range plan.Set {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return "", fmt.Errorf("environment key %q is not a valid shell identifier", key)
		}
		if strings.ContainsAny(value, "\x00\r\n") {
			return "", fmt.Errorf("environment key %s has an unsafe value", key)
		}
		keys = append(keys, key)
	}
	sort.Strings(keys)
	unsets := append([]string(nil), plan.Unset...)
	sort.Strings(unsets)
	for _, key := range unsets {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return "", fmt.Errorf("environment unset %q is not a valid shell identifier", key)
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "# Phase AI shell environment (schema %d). Generated by the Phase CLI; do not edit.\n", claudeEnvironmentSchema)
	out.WriteString("# A harness sources this file before each shell command. Proxy routing applies\n")
	out.WriteString("# only while the Phase AI proxy process is alive. Decoy credentials stay exported\n")
	out.WriteString("# so ambient provider credentials are never substituted for a Phase-managed\n")
	out.WriteString("# Connection while Phase AI is enabled; `phase ai disable` removes this file.\n")
	if len(unsets) > 0 {
		out.WriteString("unset " + strings.Join(unsets, " ") + "\n")
	}
	for _, key := range keys {
		if phaseproxy.RuntimeControlEnvironmentKey(key) {
			continue
		}
		fmt.Fprintf(&out, "export %s=%s\n", key, quotePOSIXShellValue(plan.Set[key]))
	}
	if proxyLive {
		out.WriteString(claudeProxyBlockBegin + "\n")
		fmt.Fprintf(&out, "if kill -0 %d 2>/dev/null; then\n", pid)
		for _, key := range keys {
			if !phaseproxy.RuntimeControlEnvironmentKey(key) {
				continue
			}
			fmt.Fprintf(&out, "  export %s=%s\n", key, quotePOSIXShellValue(plan.Set[key]))
		}
		out.WriteString("fi\n")
		out.WriteString(claudeProxyBlockEnd + "\n")
	} else {
		out.WriteString("# The Phase AI proxy is not running: Phase-managed provider commands fail until it recovers.\n")
	}
	// Always end successfully so a harness that chains the sourced file with the
	// command (`. file && command`) is never blocked by this file.
	out.WriteString(":\n")
	return out.String(), nil
}

// stripClaudeProxyBlock removes the proxy-routing block from rendered content.
// Hooks use it to retire routing for a daemon that is gone without needing the
// original environment plan.
func stripClaudeProxyBlock(content string) string {
	begin := strings.Index(content, claudeProxyBlockBegin+"\n")
	if begin < 0 {
		return content
	}
	end := strings.Index(content[begin:], claudeProxyBlockEnd+"\n")
	if end < 0 {
		return content
	}
	stripped := content[:begin] + content[begin+end+len(claudeProxyBlockEnd)+1:]
	if !strings.Contains(stripped, "proxy is not running") {
		stripped = strings.TrimSuffix(stripped, ":\n") +
			"# The Phase AI proxy is not running: Phase-managed provider commands fail until it recovers.\n:\n"
	}
	return stripped
}

func claudeEnvironmentPath(directory string) string {
	return filepath.Join(directory, claudeEnvironmentFile)
}

func claudeEnvironmentStatusPath(directory string) string {
	return filepath.Join(directory, claudeEnvironmentStatusFile)
}

func claudeEnvironmentJSONPath(directory string) string {
	return filepath.Join(directory, claudeEnvironmentJSONFile)
}

// renderClaudeEnvironmentJSON splits the plan the same way renderClaudeEnvironment
// does: decoys, adapters and unsets always apply; proxy routing only while the
// issuing process is alive. The plugin that reads it checks the PID itself.
func renderClaudeEnvironmentJSON(pid int, plan phaseproxy.ProcessEnvironmentPlan, proxyLive bool) (claudeEnvironmentJSON, error) {
	if proxyLive && pid <= 0 {
		return claudeEnvironmentJSON{}, errors.New("Phase AI proxy PID is required for a live environment")
	}
	payload := claudeEnvironmentJSON{Schema: claudeEnvironmentSchema, PID: pid, ProxyLive: proxyLive, Set: map[string]string{}, Proxy: map[string]string{}, Unset: []string{}}
	for key, value := range plan.Set {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return claudeEnvironmentJSON{}, fmt.Errorf("environment key %q is not a valid shell identifier", key)
		}
		if strings.ContainsAny(value, "\x00\r\n") {
			return claudeEnvironmentJSON{}, fmt.Errorf("environment key %s has an unsafe value", key)
		}
		if phaseproxy.RuntimeControlEnvironmentKey(key) {
			if proxyLive {
				payload.Proxy[key] = value
			}
			continue
		}
		payload.Set[key] = value
	}
	for _, key := range plan.Unset {
		if !phaseproxy.ValidShellEnvironmentKey(key) {
			return claudeEnvironmentJSON{}, fmt.Errorf("environment unset %q is not a valid shell identifier", key)
		}
		payload.Unset = append(payload.Unset, key)
	}
	sort.Strings(payload.Unset)
	return payload, nil
}

// writeClaudeEnvironment publishes the sourced environment and its printable
// status. The daemon calls it when a proxy cycle becomes ready (live) and when
// that cycle ends (degraded, decoys only).
func writeClaudeEnvironment(directory string, pid int, generation string, startedAt time.Time,
	plan phaseproxy.ProcessEnvironmentPlan, connections []aiproxy.EndpointConnection, proxyLive bool) error {
	content, err := renderClaudeEnvironment(pid, plan, proxyLive)
	if err != nil {
		return err
	}
	payload, err := renderClaudeEnvironmentJSON(pid, plan, proxyLive)
	if err != nil {
		return err
	}
	if err := writeOwnerOnlyBytes(claudeEnvironmentPath(directory), []byte(content)); err != nil {
		return err
	}
	if err := writeOwnerOnlyJSON(claudeEnvironmentJSONPath(directory), payload); err != nil {
		return err
	}
	if connections == nil {
		connections = []aiproxy.EndpointConnection{}
	}
	return writeOwnerOnlyJSON(claudeEnvironmentStatusPath(directory), claudeEnvironmentStatus{
		Schema: claudeEnvironmentSchema, PID: pid, Generation: generation, StartedAt: startedAt,
		ProxyLive: proxyLive, Connections: connections,
	})
}

// removeClaudeEnvironmentFiles is the `phase ai disable` exit: the next shell
// command sources nothing and runs with ambient credentials.
func removeClaudeEnvironmentFiles() error {
	directory, err := claudeHookRuntimeDir()
	if err != nil {
		return err
	}
	var errs []error
	for _, path := range []string{claudeEnvironmentPath(directory), claudeEnvironmentJSONPath(directory), claudeEnvironmentStatusPath(directory)} {
		if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// claudeEnvironmentLoaderSnippet is the only content Phase writes into the
// harness-owned environment file. It names a path; no Phase value enters that
// file. An environment inherited from `phase ai run` (PHASE_AI_ENABLED=1) wins,
// and a missing or unreadable file is a silent no-op.
func claudeEnvironmentLoaderSnippet(environmentPath string) string {
	quoted := quotePOSIXShellValue(environmentPath)
	return claudeEnvironmentLoaderMark + "\n" +
		`if [ "${PHASE_AI_ENABLED:-}" != 1 ] && [ -r ` + quoted + ` ]; then . ` + quoted + `; fi` + "\n"
}

// installClaudeEnvironmentLoader appends the loader snippet to loaderPath once.
func installClaudeEnvironmentLoader(loaderPath, environmentPath string) error {
	loaderPath = strings.TrimSpace(loaderPath)
	if loaderPath == "" {
		return nil
	}
	if !filepath.IsAbs(environmentPath) || strings.ContainsAny(environmentPath, "\x00\r\n") {
		return errors.New("Phase AI environment path is invalid")
	}
	existing, err := os.ReadFile(loaderPath)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if bytes.Contains(existing, []byte(claudeEnvironmentLoaderMark)) {
		return nil
	}
	file, err := openClaudeEnvironmentFile(loaderPath)
	if err != nil {
		return err
	}
	defer file.Close()
	snippet := claudeEnvironmentLoaderSnippet(environmentPath)
	if len(existing) > 0 && !bytes.HasSuffix(existing, []byte("\n")) {
		snippet = "\n" + snippet
	}
	_, err = file.WriteString(snippet)
	return err
}

// inspectClaudeRuntime reports daemon health from local files only: no network,
// no keyring. Hooks call it on every prompt.
func inspectClaudeRuntime(directory string) claudeRuntimeHealth {
	var health claudeRuntimeHealth
	state, err := readClaudeRuntimeState(filepath.Join(directory, claudeRuntimeStateFile))
	if err == nil && validateClaudeRuntimeState(state, "") == nil {
		health.ready = true
		var status claudeEnvironmentStatus
		if readOwnerOnlyJSON(claudeEnvironmentStatusPath(directory), &status) == nil && status.PID == state.PID && status.ProxyLive {
			health.connections = status.Connections
		}
		health.refreshedAt, health.refreshReason = lastClaudeSessionRefresh(directory, time.Now(), claudeRefreshNoticeWindow)
		return health
	}
	lock, lockErr := readClaudeRuntimeLock(filepath.Join(directory, claudeRuntimeLockFile))
	if lockErr == nil && lock.PID > 0 && processIsAlive(lock.PID) && time.Since(lock.CreatedAt) < 2*claudeHookStartTimeout {
		health.starting = true
		return health
	}
	failures, _ := filepath.Glob(filepath.Join(directory, "claude-runtime-*.error.json"))
	for _, path := range failures {
		var failure claudeRuntimeFailure
		if readOwnerOnlyJSON(path, &failure) == nil && failure.Reason == "authentication" {
			health.reason = failure.Reason
		}
	}
	return health
}

// reconcileClaudeEnvironment retires proxy routing in the sourced file when the
// daemon that published it is gone. The PID guard already protects every
// command; this bounds PID reuse to one prompt.
func reconcileClaudeEnvironment(directory string, health claudeRuntimeHealth) {
	if health.ready {
		return
	}
	var status claudeEnvironmentStatus
	if readOwnerOnlyJSON(claudeEnvironmentStatusPath(directory), &status) != nil || !status.ProxyLive {
		return
	}
	if status.PID > 0 && processIsAlive(status.PID) {
		return
	}
	content, err := os.ReadFile(claudeEnvironmentPath(directory))
	if err != nil {
		return
	}
	if err := writeOwnerOnlyBytes(claudeEnvironmentPath(directory), []byte(stripClaudeProxyBlock(string(content)))); err != nil {
		return
	}
	var payload claudeEnvironmentJSON
	if readOwnerOnlyJSON(claudeEnvironmentJSONPath(directory), &payload) == nil && payload.Schema == claudeEnvironmentSchema {
		payload.ProxyLive = false
		payload.Proxy = map[string]string{}
		_ = writeOwnerOnlyJSON(claudeEnvironmentJSONPath(directory), payload)
	}
	status.ProxyLive = false
	_ = writeOwnerOnlyJSON(claudeEnvironmentStatusPath(directory), status)
}

// kickClaudeRuntime starts or repairs the hook-owned daemon with a bounded wait
// and never fails the calling hook. When the runtime is ready it registers the
// session lease so the daemon keeps running between prompts.
func kickClaudeRuntime(ctx context.Context, directory, sessionID string, budget time.Duration) claudeRuntimeHealth {
	return kickHarnessRuntime(ctx, directory, ai.HarnessClaudeCode, sessionID, budget)
}

// kickHarnessRuntime is the harness-neutral form used by every transparent-mode
// integration (Claude Code hooks, the OpenCode plugin).
func kickHarnessRuntime(ctx context.Context, directory, harness, sessionID string, budget time.Duration) claudeRuntimeHealth {
	if ctx == nil {
		ctx = context.Background()
	}
	kickContext, cancel := context.WithTimeout(ctx, budget)
	defer cancel()
	_ = ensureHarnessRuntimeReady(kickContext)
	health := inspectClaudeRuntime(directory)
	if health.ready {
		_ = registerHarnessLease(harness, sessionID, time.Now().UTC().Add(harnessSessionLeaseTTL))
	}
	reconcileClaudeEnvironment(directory, health)
	return health
}

// claudeEnvironmentStatusLine is the printable, credential-free status handed
// to the Agent at session start and on every prompt.
func claudeEnvironmentStatusLine(health claudeRuntimeHealth) string {
	switch {
	case health.ready && len(health.connections) == 0:
		return "Phase AI: proxy ready, but this Workflow has no Connections yet. When the human asks for a Phase-managed service, load the phase-cli-ai-relay skill and create a setup request."
	case health.ready:
		names := make([]string, 0, len(health.connections))
		for _, connection := range health.connections {
			label := strings.TrimSpace(connection.Name)
			if label == "" {
				label = connection.ConnectionID
			}
			names = append(names, label+" ("+connection.ServiceType+")")
		}
		return "Phase AI: proxy ready. Shell commands automatically use Phase-managed credentials for: " + strings.Join(names, ", ") + ". Run provider tools directly; no wrapper or phase ai exec is needed." + claudeSessionRefreshNotice(health.refreshedAt, health.refreshReason)
	case health.starting:
		return "Phase AI: proxy is starting. A Phase-managed provider command issued before it is ready fails with a credential error; retry it. Other work is unaffected."
	case health.reason == "authentication":
		return "Phase AI: unavailable because the Phase login is invalid or expired; the human must run phase auth --mode token. Phase-managed provider commands fail until then, other work is unaffected. Do not substitute other credentials."
	default:
		return "Phase AI: proxy unavailable. Phase-managed provider commands fail until it recovers, other work is unaffected. Tell the human; do not substitute other credentials, disable Phase, or restart the harness."
	}
}
